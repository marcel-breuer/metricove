<?php

namespace App\Docs\OpenApi;

use Illuminate\Support\Facades\Storage;
use Symfony\Component\Yaml\Yaml;

/** Reads, normalizes and writes the checked-in OpenAPI contract at docs/api/openapi.yaml. */
class OpenApiContract
{
    public static function path(): string
    {
        return base_path('../../docs/api/openapi.yaml');
    }

    /** Path with every `{parameter}` collapsed, because Scribe may rename route parameters. */
    public static function canonicalPath(string $path): string
    {
        return '/'.trim((string) preg_replace('/\{[^}]+\}/', '{}', $path), '/');
    }

    /** @return array<string, mixed> The Scribe output of the last `scribe:generate` run. */
    public function generated(): array
    {
        $path = Storage::disk('local')->path('scribe/openapi.yaml');
        abort_unless(is_file($path), 503, 'Run php artisan scribe:generate first.');

        return $this->normalize(Yaml::parseFile($path));
    }

    /** @return array<string, mixed> */
    public function committed(): array
    {
        return $this->normalize(Yaml::parseFile(self::path()));
    }

    public function write(): void
    {
        $document = Yaml::dump($this->generated(), 20, 2, Yaml::DUMP_MULTI_LINE_LITERAL_BLOCK);
        file_put_contents(self::path(), "# Generated by `php artisan api:openapi`. Do not edit by hand.\n".$document);
    }

    /**
     * Drop volatile values (random examples, deployment URLs) so the contract only changes when
     * routes, parameters, validation or responses change.
     *
     * @param  array<mixed>  $node
     * @return array<mixed>
     */
    public function normalize(array $node, bool $root = true): array
    {
        if ($root) {
            unset($node['servers']);
            if (isset($node['components']['securitySchemes']['sessionCookie']['name'])) {
                $node['components']['securitySchemes']['sessionCookie']['name'] = '{session cookie}';
            }
        }
        foreach ($node as $key => $value) {
            if ($key === 'example' || $key === 'examples') {
                unset($node[$key]);

                continue;
            }
            if (is_array($value)) {
                $node[$key] = $this->normalize($value, false);
            }
        }

        return $node;
    }

    /** @param array<string, mixed> $document
     * @return list<string> Sorted "METHOD /path" operation keys.
     */
    public function operations(array $document): array
    {
        $operations = [];
        foreach ($document['paths'] ?? [] as $path => $item) {
            foreach ($item as $method => $operation) {
                if (in_array($method, ['get', 'post', 'put', 'patch', 'delete', 'options', 'head'], true)) {
                    $operations[] = strtoupper($method).' '.self::canonicalPath($path);
                }
            }
        }
        sort($operations);

        return $operations;
    }
}
